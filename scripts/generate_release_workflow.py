"""Generate the cargo-dist workflow with the Windows publication gate."""

import argparse
import difflib
from pathlib import Path
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
WORKFLOW = Path(".github/workflows/release.yml")
DIRTY_CI = 'allow-dirty = ["ci"]\n'
HOST = "  # Determines if we should publish/announce\n  host:\n"
WINDOWS_JOB = """  windows-package-smoke:
    needs: build-global-artifacts
    permissions:
      contents: read
    uses: ./.github/workflows/release-windows-smoke.yml

"""


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise SystemExit(f"Expected one cargo-dist match for {old!r}. Review the release gate.")
    return source.replace(old, new, 1)


def generate():
    # Keep the upstream generator and its integrity check isolated from the working tree.
    with tempfile.TemporaryDirectory(prefix="mergelane-dist-ci-") as directory:
        staging = Path(directory)
        subprocess.run(["git", "clone", "--quiet", "--shared", str(ROOT), directory], check=True)
        for name in ("Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "dist-workspace.toml",
                     ".github/release-check-steps.yml"):
            shutil.copyfile(ROOT / name, staging / name)
        config = staging / "dist-workspace.toml"
        config.write_text(replace_once(config.read_text(encoding="utf-8"), DIRTY_CI, ""),
                          encoding="utf-8")
        subprocess.run(["dist", "generate"], cwd=staging, check=True)
        source = (staging / WORKFLOW).read_text(encoding="utf-8")

    source = replace_once(
        source,
        "# This file was autogenerated by dist:",
        "# Generated by scripts/generate_release_workflow.py from dist:",
    )
    source = replace_once(
        source,
        "      - name: Cache dist\n",
        "      - name: Check generated release workflow\n"
        "        run: python3 scripts/generate_release_workflow.py --check\n"
        "      - name: Cache dist\n",
    )
    before_host, host = source.split(HOST, 1)
    host = replace_once(
        host,
        "      - build-global-artifacts\n",
        "      - build-global-artifacts\n      - windows-package-smoke\n",
    )
    host = replace_once(
        host,
        "needs.plan.outputs.publishing == 'true' && ",
        "needs.plan.outputs.publishing == 'true' && needs.windows-package-smoke.result == 'success' && ",
    )
    return before_host + WINDOWS_JOB + HOST + host


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    path = ROOT / WORKFLOW
    if args.check:
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            print("".join(difflib.unified_diff(actual.splitlines(keepends=True),
                                             expected.splitlines(keepends=True),
                                             str(WORKFLOW), "regenerated")), end="")
            raise SystemExit("Regenerate the release workflow with scripts/generate_release_workflow.py")
    else:
        path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
